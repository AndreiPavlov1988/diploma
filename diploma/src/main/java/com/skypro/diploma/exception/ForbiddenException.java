package com.skypro.diploma.exception;

/**
 * Исключение для случаев нарушения прав доступа.
 * Например: пользователь пытается редактировать чужое объявление.
 *
 * Глобальный обработчик превращает это исключение в HTTP-ответ 403 Forbidden.
 *
 * Согласно ТЗ: администратор может удалять/редактировать все,
 * обычный пользователь — только свои объявления и комментарии.
 */
public class ForbiddenException extends RuntimeException {

    /**
     * Конструктор с сообщением об ошибке.
     *
     * @param message текст ошибки (например, "Нет прав на редактирование")
     */
    public ForbiddenException(String message) {
        super(message);
    }
}
